"""Offline machine translation with Argos Translate model packages.

Each ``.argosmodel`` package is a zip holding a CTranslate2 model plus either a
SentencePiece model (``sentencepiece.model``) or BPE codes (``bpe.model``, used
with the Moses tokenizer).  MDMT runs them directly with CTranslate2; the
``argostranslate`` package is not used (it pulls in stanza and torch), and the
packages' bundled stanza sentence splitters are ignored in favour of
NLP.text_utils.

Packages are listed in Translation/argos_index.json (a pinned snapshot of the
Argos index, regenerated by update_argos_index.py) and downloaded on demand into
``<models>/translation/<from>_<to>/``.  Most pairs translate to or from English;
other pairs pivot through English, which compounds errors.
"""
import functools
import json
import os
import re
import shutil
import threading
import zipfile

INDEX_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "argos_index.json")
PIVOT = "en"
DEFAULT_SUFFIX = "_translated"
MAX_TOKENS = 200        # longer sentences are split before translation
BATCH_SIZE = 16

# py3langid code -> Argos code, where they differ.
_LANGID_TO_ARGOS = {"no": "nb", "nn": "nb"}
# Argos variants detection cannot tell apart: (detected code, variant code).
_VARIANTS = {"pt": "pb", "zh": "zt"}


# ---------------------------------------------------------------- index ----

@functools.lru_cache(maxsize=None)
def load_index() -> tuple:
    with open(INDEX_PATH, encoding="utf-8") as f:
        return tuple(json.load(f)["packages"])


def language_names() -> dict:
    """code -> name for every language in the index, sorted by name."""
    names = {}
    for p in load_index():
        names[p["from_code"]] = p["from_name"]
        names[p["to_code"]] = p["to_name"]
    return dict(sorted(names.items(), key=lambda kv: kv[1]))


def package_info(src: str, tgt: str) -> dict | None:
    return next((p for p in load_index() if p["from_code"] == src and p["to_code"] == tgt), None)


# ------------------------------------------------------------- packages ----

def translation_root(models_root: str | None = None) -> str:
    if models_root is None:
        from config import get_models_dir
        models_root = get_models_dir()
    path = os.path.join(models_root, "translation")
    os.makedirs(path, exist_ok=True)
    return path


def package_dir(src: str, tgt: str, models_root: str | None = None) -> str:
    return os.path.join(translation_root(models_root), f"{src}_{tgt}")


def _is_package(path: str) -> bool:
    return os.path.isfile(os.path.join(path, "model", "model.bin")) and (
        os.path.isfile(os.path.join(path, "sentencepiece.model"))
        or os.path.isfile(os.path.join(path, "bpe.model")))


def is_installed(src: str, tgt: str, models_root: str | None = None) -> bool:
    return _is_package(package_dir(src, tgt, models_root))


def installed_pairs(models_root: str | None = None) -> set:
    root = translation_root(models_root)
    pairs = set()
    for name in os.listdir(root):
        if "_" in name and not name.endswith(".part") and _is_package(os.path.join(root, name)):
            pairs.add(tuple(name.split("_", 1)))
    return pairs


def _safe_extract(archive: zipfile.ZipFile, dest: str):
    """Extract a zip, refusing members that would escape *dest*."""
    root = os.path.realpath(dest)
    for member in archive.infolist():
        target = os.path.realpath(os.path.join(dest, member.filename))
        if target != root and not target.startswith(root + os.sep):
            raise ValueError(f"unsafe path in package: {member.filename}")
    archive.extractall(dest)


def download_package(src: str, tgt: str, models_root: str | None = None, on_progress=None) -> str:
    """Download and unpack the src->tgt package atomically; returns its directory."""
    from common.downloads import download_file

    info = package_info(src, tgt)
    if info is None:
        raise KeyError(f"no Argos package for {src} -> {tgt}")
    dest = package_dir(src, tgt, models_root)
    if _is_package(dest):
        return dest
    archive_path = dest + ".argosmodel"
    work = dest + ".part"
    shutil.rmtree(work, ignore_errors=True)
    try:
        download_file(info["url"], archive_path, on_progress=on_progress)
        with zipfile.ZipFile(archive_path) as archive:
            _safe_extract(archive, work)
        # Packages contain one top-level folder whose name varies between versions.
        inner = next((os.path.join(work, d) for d in os.listdir(work)
                      if _is_package(os.path.join(work, d))), None)
        if inner is None:
            raise ValueError(f"{info['code']}: unexpected package layout")
        shutil.rmtree(os.path.join(inner, "stanza"), ignore_errors=True)  # unused, torch format
        shutil.rmtree(dest, ignore_errors=True)
        os.replace(inner, dest)
    finally:
        shutil.rmtree(work, ignore_errors=True)
        try:
            os.remove(archive_path)
        except OSError:
            pass
    return dest


def remove_package(src: str, tgt: str, models_root: str | None = None):
    shutil.rmtree(package_dir(src, tgt, models_root), ignore_errors=True)


def route(src: str, tgt: str, models_root: str | None = None, available=None) -> list | None:
    """Packages to chain for src->tgt: direct, or pivoting through English.

    *available* defaults to the installed pairs; pass the index pairs to ask
    what would be needed.
    """
    if src == tgt:
        return []
    pairs = installed_pairs(models_root) if available is None else available
    if (src, tgt) in pairs:
        return [(src, tgt)]
    if src != PIVOT and tgt != PIVOT and (src, PIVOT) in pairs and (PIVOT, tgt) in pairs:
        return [(src, PIVOT), (PIVOT, tgt)]
    return None


def index_pairs() -> set:
    return {(p["from_code"], p["to_code"]) for p in load_index()}


# ------------------------------------------------------------ language ID ----

def detect_language(text: str, candidates=None) -> str | None:
    """Most likely language of *text* (Argos code), optionally among *candidates*."""
    import py3langid

    sample = text[:4000]
    if not sample.strip():
        return None
    for code, _score in py3langid.rank(sample):
        code = _LANGID_TO_ARGOS.get(code, code)
        if candidates is None or code in candidates:
            return code
        if code in _VARIANTS and _VARIANTS[code] in candidates:
            return _VARIANTS[code]
    return None


# ----------------------------------------------------------- tokenizers ----

class _SentencePiece:
    def __init__(self, path):
        import sentencepiece
        self.sp = sentencepiece.SentencePieceProcessor(model_file=path)

    def encode(self, text):
        return self.sp.encode(text, out_type=str)

    def decode(self, tokens):
        # Same post-processing as argostranslate's SentencePieceTokenizer.
        return self.sp.decode_pieces(tokens).replace("▁", " ").replace("_", " ")


class _MosesBpe:
    def __init__(self, path, src, tgt):
        from sacremoses import MosesDetokenizer, MosesPunctNormalizer, MosesTokenizer

        from Translation.bpe import BPE
        with open(path, encoding="utf-8") as f:
            self.bpe = BPE(f.read())
        self.normalizer = MosesPunctNormalizer(src)
        self.tokenizer = MosesTokenizer(src)
        self.detokenizer = MosesDetokenizer(tgt)

    def encode(self, text):
        tokens = self.tokenizer.tokenize(self.normalizer.normalize(text), return_str=True)
        return self.bpe.segment_tokens(tokens.strip("\r\n ").split(" "))

    def decode(self, tokens):
        return self.detokenizer.detokenize(" ".join(tokens).replace("@@ ", "").split(" "))


class PackageTranslator:
    """One installed package: CTranslate2 model plus its tokenizer."""

    def __init__(self, path: str, src: str, tgt: str):
        import ctranslate2

        self.translator = ctranslate2.Translator(os.path.join(path, "model"), device="cpu", compute_type="auto")
        sp = os.path.join(path, "sentencepiece.model")
        self.tokenizer = _SentencePiece(sp) if os.path.isfile(sp) else _MosesBpe(
            os.path.join(path, "bpe.model"), src, tgt)
        self._lock = threading.Lock()

    def translate(self, sentences: list[str]) -> list[str]:
        if not sentences:
            return []
        batch = [self.tokenizer.encode(s) for s in sentences]
        with self._lock:
            results = self.translator.translate_batch(
                batch, beam_size=4, max_batch_size=BATCH_SIZE, replace_unknowns=True, length_penalty=0.2,
                max_decoding_length=max(256, 2 * max(len(t) for t in batch)),
            )
        return [self.tokenizer.decode(r.hypotheses[0]).strip() for r in results]

    def count_tokens(self, text: str) -> int:
        return len(self.tokenizer.encode(text))


_translators: dict = {}
_translators_lock = threading.Lock()


def get_translator(src: str, tgt: str, models_root: str | None = None) -> PackageTranslator:
    path = package_dir(src, tgt, models_root)
    with _translators_lock:
        if path not in _translators:
            if not _is_package(path):
                raise FileNotFoundError(f"translation package {src}->{tgt} is not installed")
            if len(_translators) >= 3:
                _translators.pop(next(iter(_translators)))
            _translators[path] = PackageTranslator(path, src, tgt)
        return _translators[path]


# --------------------------------------------------------------- text ----

_LINE_END = re.compile(r"[.!?…:;。！？\"'”’)\]]\s*$")


def _paragraphs(text: str) -> list[str]:
    """Split text into paragraphs, re-joining lines that were hard-wrapped.

    A line break is kept when the line ends a sentence (or the text has a blank
    line); otherwise the line is treated as wrapped, as in most PDF text.
    """
    paragraphs, current = [], []
    for line in text.replace("\r\n", "\n").split("\n"):
        stripped = line.strip()
        if not stripped:
            if current:
                paragraphs.append(" ".join(current))
                current = []
            continue
        current.append(stripped)
        if _LINE_END.search(stripped):
            paragraphs.append(" ".join(current))
            current = []
    if current:
        paragraphs.append(" ".join(current))
    return paragraphs


def _chunks_for(translator: PackageTranslator, sentence: str) -> list[str]:
    """The sentence, or pieces of it at word boundaries if it is too long for the model."""
    if translator.count_tokens(sentence) <= MAX_TOKENS:
        return [sentence]
    pieces, current = [], []
    for word in sentence.split():
        if current and translator.count_tokens(" ".join(current + [word])) > MAX_TOKENS:
            pieces.append(" ".join(current))
            current = []
        current.append(word)
    if current:
        pieces.append(" ".join(current))
    return pieces


def _translate_with(translator: PackageTranslator, text: str) -> str:
    from NLP.text_utils import sentences as split_sentences

    out = []
    for paragraph in _paragraphs(text):
        units = [chunk for s in split_sentences(paragraph) for chunk in _chunks_for(translator, s)]
        out.append(" ".join(translator.translate(units)))
    return "\n".join(out)


def translate_text(text: str, src: str, tgt: str, models_root: str | None = None) -> str:
    """Translate *text* from src to tgt with installed packages (pivoting if needed)."""
    steps = route(src, tgt, models_root)
    if steps is None:
        raise LookupError(f"no installed translation route from {src} to {tgt}")
    for a, b in steps:
        text = _translate_with(get_translator(a, b, models_root), text)
    return text


# ------------------------------------------------------------- folders ----

def translate_directory(directory: str, src: str | None, tgt: str, suffix: str = DEFAULT_SUFFIX,
                        models_root: str | None = None, on_progress=None) -> list[dict]:
    """Translate every .txt and .pdf file under *directory*.

    src=None detects each file's language among those with an installed route.
    Output: ``name<suffix>.txt`` next to the input (``.txt`` for PDFs too).
    Files that already end with the suffix are skipped (they are outputs).
    """
    from common.pdf_text import extract_text

    files = []
    for root, _dirs, names in os.walk(directory):
        for name in names:
            stem, ext = os.path.splitext(name)
            if ext.lower() in (".txt", ".pdf") and not stem.endswith(suffix):
                files.append(os.path.join(root, name))
    files.sort()

    installed = installed_pairs(models_root)
    sources = {a for a, _b in installed} | {b for _a, b in installed}
    candidates = {s for s in sources if route(s, tgt, models_root, installed) is not None}
    results = []
    for i, path in enumerate(files):
        if on_progress:
            on_progress(i, len(files), os.path.basename(path))
        result = {"input": path}
        try:
            text = extract_text(path) if path.lower().endswith(".pdf") else open(path, encoding="utf-8").read()
            if not text.strip():
                result.update(status="skipped", message="no text (scanned PDF? run OCR first)")
                results.append(result)
                continue
            lang = src or detect_language(text, candidates)
            if lang is None:
                result.update(status="error", message="could not detect a language with an installed model")
                results.append(result)
                continue
            steps = route(lang, tgt, models_root, installed)
            if steps is None:
                result.update(status="error", language=lang,
                              message=f"no installed model for {lang} -> {tgt}")
                results.append(result)
                continue
            translated = translate_text(text, lang, tgt, models_root)
            stem = os.path.splitext(path)[0]
            out_path = f"{stem}{suffix}.txt"
            with open(out_path, "w", encoding="utf-8") as f:
                f.write(translated)
            result.update(status="success", language=lang, output=out_path, pivot=len(steps) > 1)
        except Exception as e:
            result.update(status="error", message=str(e))
        results.append(result)
    if on_progress:
        on_progress(len(files), len(files), "Done")
    return results
